def set_text(p, text):
    for r in p.runs[1:]:
        r.text = ''
    if p.runs:
        p.runs[0].text = text
    else:
        p.add_run(text)


def para(doc, start):
    return next(p for p in doc.paragraphs if ''.join(r.text for r in p.runs).startswith(start))


def insert_after(p, style, text):
    new = copy.deepcopy(p._p)
    p._p.addnext(new)
    np_ = Paragraph(new, p._parent)
    set_text(np_, text)
    np_.style = style
    return np_


