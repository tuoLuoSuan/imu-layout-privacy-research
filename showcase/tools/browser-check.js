async (page) => {
  const errors=[];const posts=[];const httpFailures=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',res=>{if(res.status()>=400)httpFailures.push({url:res.url(),status:res.status()});});
  page.on('request',req=>{if(req.method()==='POST')posts.push(req.url());});
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
  check(await page.locator('#scene canvas').count()===1,'3D canvas missing');
  check(await page.locator('#overview').evaluate(el=>el.classList.contains('active')),'progress is not initial page');
  check((await page.locator('#overview').textContent()).includes('30分钟'),'long trial status missing');
  check((await page.locator('#overview').textContent()).includes('4 次正常退出'),'exit trials status missing');
  check((await page.locator('#prepare').textContent()).includes('尚未唯一识别'),'geometry limitation missing');
  await page.screenshot({path:'output/playwright/2026-10-15-radar-closeout/desktop-progress.png',fullPage:true});
  await page.locator('[data-tab="space"]').click();
  await page.locator('#show-path').uncheck();check(!await page.locator('#show-path').isChecked(),'route control');
  await page.locator('#show-path').check();
  await page.locator('#show-objects').uncheck();check(!await page.locator('#show-objects').isChecked(),'object control');
  await page.locator('#show-objects').check();
  const canvas=page.locator('#scene canvas');const box=await canvas.boundingBox();
  await page.mouse.move(box.x+box.width*.5,box.y+box.height*.5);await page.mouse.down();
  await page.mouse.move(box.x+box.width*.65,box.y+box.height*.55,{steps:8});await page.mouse.up();
  await page.locator('#reset-view').click();
  await page.screenshot({path:'output/playwright/2026-10-15-radar-closeout/desktop-space.png',fullPage:true});
  await page.locator('[data-tab="signals"]').click();
  check(await page.locator('#count').textContent()==='1334','phone acceleration row count');
  check(await page.locator('#signal-unit').textContent()==='m/s²','acceleration unit');
  await page.locator('#signal-dataset').selectOption('phone-gyro');
  check(await page.locator('#count').textContent()==='1335','phone gyro row count');
  check(await page.locator('#signal-unit').textContent()==='rad/s','gyro unit');
  check((await page.locator('#channel-title').textContent()).includes('角速度'),'gyro title');
  await page.locator('#signal-dataset').selectOption('band');
  check(await page.locator('#count').textContent()==='30','historical row count');
  check(await page.locator('#signal-unit').textContent()==='待确认','historical unit');
  check(await page.locator('#span').textContent()==='1889 ms','real callback span');
  check(await page.locator('#rate').textContent()==='15.352 /s','real callback rate');
  await page.locator('#sample-slider').evaluate(el=>{el.value='29';el.dispatchEvent(new Event('input',{bubbles:true}));});
  check((await page.locator('#sample-value').textContent()).includes('1935 ms'),'last callback selection');
  await page.locator('#csv-file').setInputFiles('D:/Project/imu环境重建/collection/band9pro-probe/recordings/2026-10-13_first_real_video/1791866158764_fddc8d.csv');
  await page.waitForFunction(()=>document.getElementById('signal-badge').textContent.includes('来源待核'));
  check((await page.locator('#signal-badge').textContent()).includes('来源待核'),'CSV source label');
  check(await page.locator('#count').textContent()==='30','CSV row count');
  await page.locator('#csv-file').setInputFiles({name:'bad.csv',mimeType:'text/csv',buffer:Buffer.from('callback_elapsed_ms,x,y,z\n64,1,2,3\n32,1,2,3')});
  await page.waitForFunction(()=>document.getElementById('import-message').textContent.includes('时间'));
  check((await page.locator('#import-message').textContent()).includes('时间'),'bad CSV was not rejected');
  check(await page.locator('#count').textContent()==='30','bad CSV altered data');
  await page.locator('#restore-sample').click();
  await page.locator('#signal-dataset').selectOption('phone-accel');
  await page.screenshot({path:'output/playwright/2026-10-15-radar-closeout/desktop-signals.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile signal overflow');
  await page.screenshot({path:'output/playwright/2026-10-15-radar-closeout/mobile-signals.png',fullPage:true});
  await page.locator('[data-tab="space"]').click();
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile scene overflow');
  await page.screenshot({path:'output/playwright/2026-10-15-radar-closeout/mobile-space.png',fullPage:true});
  for(const name of ['overview','model','prepare','artifact']){await page.locator(`[data-tab="${name}"]`).click();check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`mobile ${name} overflow`);}
  check((await page.locator('#artifact').textContent()).includes('私有仓库'),'remote status missing');
  await page.screenshot({path:'output/playwright/2026-10-15-radar-closeout/mobile-artifact.png',fullPage:true});
  check(errors.length===0,'browser errors: '+errors.join(';'));
  check(posts.length===0,'unexpected uploads');
  check(httpFailures.length===0,'HTTP failures: '+JSON.stringify(httpFailures));
  return {status:'passed',phone_accel_rows:1334,phone_gyro_rows:1335,historical_rows:30,csv_import:'passed',bad_clock_rejection:'passed',mobile_width:390,page_errors:errors,upload_requests:posts,http_failures:httpFailures};
}
